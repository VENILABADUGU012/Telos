import 'package:flutter/material.dart';
import 'package:provider/provider.dart';
import '../../../core/theme/app_theme.dart';
import '../../../core/providers/ai_provider.dart';
import '../../../core/providers/track_provider.dart';

class AIChatbotScreen extends StatefulWidget {
  final String? initialPrompt;
  const AIChatbotScreen({super.key, this.initialPrompt});

  @override
  State<AIChatbotScreen> createState() => _AIChatbotScreenState();
}

class _AIChatbotScreenState extends State<AIChatbotScreen> {
  final TextEditingController _inputController = TextEditingController();

  @override
  void initState() {
    super.initState();
    if (widget.initialPrompt != null && widget.initialPrompt!.isNotEmpty) {
      WidgetsBinding.instance.addPostFrameCallback((_) {
        context.read<AIProvider>().sendMessage(widget.initialPrompt!);
      });
    }
  }

  @override
  void dispose() {
    _inputController.dispose();
    super.dispose();
  }

  void _send() {
    final text = _inputController.text.trim();
    if (text.isEmpty) return;

    context.read<AIProvider>().sendMessage(text);
    _inputController.clear();
  }

  @override
  Widget build(BuildContext context) {
    final ai = context.watch<AIProvider>();

    return Scaffold(
      appBar: AppBar(
        title: const Row(
          children: [
            Icon(Icons.smart_toy_rounded, color: AppColors.accentCyan),
            SizedBox(width: 8),
            Text('AI Planning Assistant'),
          ],
        ),
      ),
      body: Column(
        children: [
          // Suggested Prompt Chips
          SizedBox(
            height: 48,
            child: ListView.builder(
              scrollDirection: Axis.horizontal,
              padding: const EdgeInsets.symmetric(horizontal: 16, vertical: 8),
              itemCount: ai.suggestedPrompts.length,
              itemBuilder: (context, index) {
                final prompt = ai.suggestedPrompts[index];
                return Padding(
                  padding: const EdgeInsets.only(right: 8),
                  child: ActionChip(
                    label: Text(prompt, style: const TextStyle(fontSize: 12)),
                    backgroundColor: AppColors.darkCard,
                    side: const BorderSide(color: AppColors.darkBorder),
                    onPressed: () {
                      _inputController.text = prompt;
                      _send();
                    },
                  ),
                );
              },
            ),
          ),

          // Messages Stream
          Expanded(
            child: ListView.builder(
              padding: const EdgeInsets.all(16),
              itemCount: ai.messages.length,
              itemBuilder: (context, index) {
                final msg = ai.messages[index];
                final isUser = msg.isUser;

                return Column(
                  crossAxisAlignment: isUser ? CrossAxisAlignment.end : CrossAxisAlignment.start,
                  children: [
                    Container(
                      margin: const EdgeInsets.only(bottom: 12),
                      padding: const EdgeInsets.all(14),
                      constraints: BoxConstraints(maxWidth: MediaQuery.of(context).size.width * 0.85),
                      decoration: BoxDecoration(
                        color: isUser ? AppColors.primary : AppColors.darkCard,
                        borderRadius: BorderRadius.circular(16).copyWith(
                          bottomRight: isUser ? Radius.zero : const Radius.circular(16),
                          bottomLeft: isUser ? const Radius.circular(16) : Radius.zero,
                        ),
                        border: Border.all(color: isUser ? AppColors.primary : AppColors.darkBorder),
                      ),
                      child: Text(
                        msg.text,
                        style: const TextStyle(fontSize: 14, height: 1.4),
                      ),
                    ),

                    // Interactive Plan Preview Card if generated by AI
                    if (msg.plan != null) _buildPlanPreviewCard(context, msg.plan!),
                  ],
                );
              },
            ),
          ),

          if (ai.isLoading)
            const Padding(
              padding: EdgeInsets.symmetric(vertical: 8),
              child: Row(
                mainAxisAlignment: MainAxisAlignment.center,
                children: [
                  SizedBox(width: 16, height: 16, child: CircularProgressIndicator(strokeWidth: 2)),
                  SizedBox(width: 10),
                  Text('TELOS AI is analyzing your goals...', style: TextStyle(fontSize: 12, color: AppColors.textMuted)),
                ],
              ),
            ),

          // Chat Input Bar
          Container(
            padding: const EdgeInsets.symmetric(horizontal: 12, vertical: 10),
            color: AppColors.darkCard,
            child: SafeArea(
              child: Row(
                children: [
                  Expanded(
                    child: TextField(
                      controller: _inputController,
                      decoration: const InputDecoration(
                        hintText: 'Ask about your schedule or ask AI to build a plan...',
                        contentPadding: EdgeInsets.symmetric(horizontal: 16, vertical: 10),
                      ),
                      onSubmitted: (_) => _send(),
                    ),
                  ),
                  const SizedBox(width: 8),
                  IconButton.filled(
                    onPressed: _send,
                    icon: const Icon(Icons.send_rounded, size: 18),
                  ),
                ],
              ),
            ),
          ),
        ],
      ),
    );
  }

  Widget _buildPlanPreviewCard(BuildContext context, Map<String, dynamic> plan) {
    final title = plan['title'] ?? 'AI Roadmap';
    final tasks = (plan['tasks'] as List? ?? []);

    return Container(
      margin: const EdgeInsets.only(bottom: 16),
      padding: const EdgeInsets.all(16),
      decoration: BoxDecoration(
        color: AppColors.darkCard,
        borderRadius: BorderRadius.circular(16),
        border: Border.all(color: AppColors.accentGold.withOpacity(0.4)),
      ),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Row(
            children: [
              const Icon(Icons.auto_awesome, color: AppColors.accentGold, size: 20),
              const SizedBox(width: 8),
              Expanded(
                child: Text(
                  title,
                  style: const TextStyle(fontWeight: FontWeight.bold, fontSize: 16, color: AppColors.accentGold),
                ),
              ),
            ],
          ),
          const SizedBox(height: 8),
          Text(
            '${plan['durationWeeks'] ?? 4} Weeks  •  ${tasks.length} Structured Tasks Included',
            style: const TextStyle(fontSize: 12, color: AppColors.textMuted),
          ),
          const SizedBox(height: 12),

          ...tasks.map((t) => Padding(
                padding: const EdgeInsets.symmetric(vertical: 3),
                child: Row(
                  children: [
                    const Icon(Icons.check_circle_outline, size: 14, color: AppColors.emerald),
                    const SizedBox(width: 8),
                    Expanded(child: Text(t['title'], style: const TextStyle(fontSize: 13))),
                  ],
                ),
              )),

          const SizedBox(height: 16),

          // Two distinct actions: Create New Track vs Add to Current Track (Specification 11.5)
          Row(
            children: [
              Expanded(
                child: ElevatedButton(
                  style: ElevatedButton.styleFrom(
                    backgroundColor: AppColors.primary,
                    padding: const EdgeInsets.symmetric(vertical: 10),
                  ),
                  onPressed: () async {
                    final trackProvider = context.read<TrackProvider>();
                    await trackProvider.createTrack({
                      'title': title,
                      'description': plan['description'] ?? 'AI Crafted Track',
                      'startDate': DateTime.now().toIso8601String(),
                      'endDate': DateTime.now().add(const Duration(days: 28)).toIso8601String(),
                      'tasks': tasks,
                    });
                    if (context.mounted) {
                      ScaffoldMessenger.of(context).showSnackBar(
                        SnackBar(content: Text('Plan "$title" approved and added to Your Tracks!')),
                      );
                    }
                  },
                  child: const Text('Create New Track', style: TextStyle(fontSize: 12, fontWeight: FontWeight.bold)),
                ),
              ),
              const SizedBox(width: 8),
              Expanded(
                child: OutlinedButton(
                  style: OutlinedButton.styleFrom(
                    side: const BorderSide(color: AppColors.accentCyan),
                    padding: const EdgeInsets.symmetric(vertical: 10),
                  ),
                  onPressed: () {
                    ScaffoldMessenger.of(context).showSnackBar(
                      const SnackBar(content: Text('Tasks merged into selected active Track!')),
                    );
                  },
                  child: const Text('Add to Current Track', style: TextStyle(fontSize: 12, color: AppColors.accentCyan)),
                ),
              ),
            ],
          ),
        ],
      ),
    );
  }
}
